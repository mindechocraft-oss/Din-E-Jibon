export function getDailyQuizQuestions(date: Date = new Date()): QuizQuestion[] {
  const dayIndex = Math.floor(date.getTime() / (1000 * 60 * 60 * 24));
  const total = ISLAMIC_QUIZ_QUESTIONS.length;
  const start = (dayIndex * 5) % total;
  const selected: QuizQuestion[] = [];
  for (let i = 0; i < 5; i++) {
    selected.push(ISLAMIC_QUIZ_QUESTIONS[(start + i) % total]);
  }
  return selected;
}
